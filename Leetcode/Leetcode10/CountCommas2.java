public class CountCommas2 {
    public long countCommas(long n) {
        if (n < 1000) return 0;
        else if (n < 1000000) return n - 999;
        else if (n < 1000000000) {
            return 1000000 - 1000 + 2 * (n - 999999);
        } else if (n < 1000000000000l) {
            return 1000000 - 1000 + 2 * (1000000000 - 1000000) + 3 * (n - 999999999);
        } else if (n < 1000000000000000l) {
            return 1000000 - 1000 + 2 * (1000000000 - 1000000) + 3 * (1000000000000l - 1000000000) + 4 * (n - 999999999999l);
        } else {
            return 1000000 - 1000 + 2 * (1000000000 - 1000000) + 3 * (1000000000000l - 1000000000) + 4 * (1000000000000000l - 1000000000000l) + 5;
        }
    }
}
